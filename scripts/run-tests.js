import {readdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {runManagedTest} from './lib/test-workspace.js';
const root=fileURLToPath(new URL('../',import.meta.url));
const available=readdirSync(join(root,'test'),{withFileTypes:true}).filter(item=>item.isFile()&&item.name.endsWith('.test.js')).map(item=>item.name).sort();
const requested=process.argv.slice(2);
if(requested.some(name=>!available.includes(name)))throw Error('Use test basenames from the test directory.');
const files=(requested.length?requested:available).map(name=>join(root,'test',name));
const result=await runManagedTest({root,label:requested.length?'focused-tests':'full-tests',args:['--test',...files]});
process.exitCode=result.code;
